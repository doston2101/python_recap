uzum = {
    'Laptop', 'Phone', 'Tablet', 'Monitor',
    'Keyboard', 'Mouse', 'Printer', 'Camera',
    'Smart Watch', 'Power Bank', 'Flash Drive',
    'Headphones', 'Router'
}

olcha = {
    'Laptop', 'Phone', 'Mouse', 'Printer',
    'Headphones', 'Smart Watch', 'SSD',
    'Router', 'Microphone', 'Webcam'
}

asaxiy = {
    'Laptop', 'Tablet', 'Monitor', 'Keyboard',
    'Camera', 'Flash Drive', 'SSD',
    'Projector', 'Microphone', 'TV', 'Speaker'
}

# 1-topshiriq. Pairwise assortment differences
# Har bir ikkita marketplace o‘rtasidagi simmetrik farqni aniqlang.
# - Uzum va Olcha.
uzum_olcha = uzum.symmetric_difference(olcha)
print(f'Uzum va olcha : {uzum_olcha}')
print(f'len : {len(uzum_olcha)}')
# - Uzum va Asaxiy.
uzum_asaxiy = uzum.symmetric_difference(asaxiy)
print(f'Uzum va asaxiy : {uzum_asaxiy}')
print(f'len: {len(uzum_asaxiy)}')
# - Olcha va Asaxiy.
olcha_asaxiy = olcha.symmetric_difference(asaxiy)
print(f'Olcha va asaxiy : {olcha_asaxiy}')
print(f'len : {len(olcha_asaxiy)}')

# 5-topshiriq. Market differentiation ratio
# Har bir juftlikning simmetrik farqini ularning umumiy assortimentiga nisbatan foizda hisoblang.
# Bu ko‘rsatkich ikkita marketplace assortimentining qanchalik farq qilishini ko‘rsatadi.

total_uzum_olcha = len(uzum.union(olcha))
total_uzum_asaxiy = len(uzum.union(asaxiy))
total_olcha_asaxiy = len(olcha.union(asaxiy))

uzum_olcha_ratio = (len(uzum_olcha) / total_uzum_olcha)* 100
uzum_asaxiy_ratio = (len(uzum_asaxiy) / total_uzum_asaxiy)* 100
olcha_asaxiy_ratio = (len(olcha_asaxiy) / total_olcha_asaxiy)* 100

print(f'Uzum va olcha : {uzum_olcha_ratio:.2f}%')
print(f'Uzum va asaxiy : {uzum_asaxiy_ratio:.2f}%')
print(f'olcah asaxiy : {olcha_asaxiy_ratio:.2f}%')

