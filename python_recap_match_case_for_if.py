# 4-vazifa. Final Business Classification

# Har bir marketplace uchun yakuniy qaror chiqaring:
# - Revenue Excellent va Return Low Risk bo‘lsa — Increase Investment.
# - Revenue Good va Return Medium Risk bo‘lsa — Maintain Investment.
# - Revenue Average yoki Return High Risk bo‘lsa — Improve Performance.
# - Revenue Poor bo‘lsa — Critical Review.
# Bu vazifada match-case ichida if ishlatish kerak

final_business = {}

for i in marketplaces:

    plan = final_plan[f"plan_{i.lower()}"]["completed"]
    risk = final_return[f"return_percentage_{i.lower()}"]["completed"]
    engagement = customer_engagement_return[f"customer_engagement_{i.lower()}"]["completed"]

    match plan:
        case "Excellent" if risk == "Low risk":
            decision = "Increase Investment"
        case "Good" if risk == "Medium Risk":
            decision = "Maintain Investment"
        case _ if plan == "Average" or risk == "High Risk":
            decision = "Improve Performance"
        case "Poor":
            decision = "Critical Review"
        case _:
            decision = "Review Required"


    final_business[i] = {
        "revenue": plan,
        "return_risk": risk,
        "customer_engagement": engagement,
        "decision": decision
    }

print(final_business)

