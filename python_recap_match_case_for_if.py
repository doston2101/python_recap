# 1-vazifa. Revenue Performance
# Har bir marketplace uchun reja bajarilish foizini hisoblang.
# match-case yordamida tasniflang:
# Reja bajarilishi	Natija
# 100% va yuqori	Excellent
# 80–99.99%	Good
# 60–79.99%	Average
# 60% dan past	Poor

plan_platform = {
  "plan_uzum": round((marketplaces["Uzum"]["revenue"] / marketplaces["Uzum"]["target"]) *100 , 2),
  "plan_olcha" : round((marketplaces["Olcha"]["revenue"] / marketplaces["Olcha"]["target"]) *100, 2),
  "plan_asaxiy" : round((marketplaces["Asaxiy"]["revenue"] / marketplaces["Asaxiy"]["target"]) *100, 2)
}
print(plan_platform)

final_plan = {}
for i ,j in plan_platform.items():
  match float(j):
    case x if x >=100 :
      comleted = "Excellent"
    case x if x >= 80 :
      comleted = "Good"
    case x if x >= 60 :
      comleted = "Average"
    case _:
      comleted = "Poor"

  final_plan[i] = {
      "plan" : j,
      "completed" : comleted
  }

print(final_plan)
print('------------------------------------')
# 2-vazifa. Return Rate Analysis
# Har bir marketplace uchun qaytarilgan buyurtmalar foizini hisoblang.
# Qaytarish foizi	Natija
# 3% gacha	Low Risk
# 3–5%	Medium Risk
# 5% dan yuqori	High Risk

return_percentage= {
  "return_percentage_uzum": round((marketplaces["Uzum"]["returns"] / marketplaces["Uzum"]["orders"]) *100 , 2),
  "return_percentage_olcha" : round((marketplaces["Olcha"]["returns"] / marketplaces["Olcha"]["orders"]) *100, 2),
  "return_percentage_asaxiy" : round((marketplaces["Asaxiy"]["returns"] / marketplaces["Asaxiy"]["orders"]) *100, 2)
}

final_return = {}

for i ,j in return_percentage.items():
  match float(j):
    case x if x <= 3 :
      comleted = "Low risk"
    case x if x <= 5 :
      comleted = "Medium Risk"
    case _ :
      comleted = "High Risk"

  final_return[i]= {
      "plan" : j,
      "completed" : comleted
  }
print(final_return)

print('---------------------------')

