for i in total_product_sales:
    if total_product_sales[i] > max_sales_product.get('sales', 0):
      max_sales_product['product'] = i
      max_sales_product['sales'] = total_product_sales[i]
print(f'Max sales product: {max_sales_product}')
print('------------------------------')

# float('inf') — agar sales kaliti hali mavjud bo‘lmasa, cheksizlik qiymatini qaytaradi.
