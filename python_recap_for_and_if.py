# 3-vazifa. Product Performance Ranking
# Har bir mahsulot bo‘yicha uchala marketplace'dagi sotuvlar sonini birlashtiring
# Talablar:
# - Har bir mahsulotning jami sotuvini hisoblang.
# - Qaysi mahsulot eng ko‘p sotilganini aniqlang.
