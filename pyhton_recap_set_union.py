print("-----------------------------")

# 9/10
# - Uchala platformaning umumiy mahsulot bazasini yarat.
print(total_unique)
print("-----------------------------")

# - Har bir platformaning umumiy bazaga qo‘shgan hissasini aniqlagin.

print(f'onliy_uzum: {only_uzum}''\n',
      f'onliy_olcha: {only_olcha}''\n',
      f'onliy_asaxiy: {only_asaxiy}')
print("-----------------------------")

uzum_per = (len(only_uzum) / len(total_unique)) * 100
olcha_per = (len(only_olcha) / len(total_unique)) * 100
asaxiy_per = (len(only_asaxiy) / len(total_unique)) * 100

print(f'uzum :{uzum_per:.2f}%''\n',
      f'olcha:{olcha_per:.2f}%''\n',
      f'asaxiy:{asaxiy_per:.2f}%')


# - Eng ko‘p noyob mahsulot qo‘shgan platformani aniqlagin.

max_count = {'uzum_count' :len(only_uzum),
             'olcha_count' : len(only_olcha),
             'asaxiy_count' : len(only_asaxiy)}

max_count_value = max(max_count.values())
max_count_app = max(max_count, key = max_count.get)

print(max_count_value)
print(max_count_app)

# - Platformalarning noyob mahsulotlar qo‘shish ko‘rsatkichlarini foizda taqqosla.
max_per = max (uzum_per, olcha_per, asaxiy_per)
min_per = min (uzum_per, olcha_per, asaxiy_per)

per_difference = max_per - min_per

relative_difference = (per_difference / min_per) * 100

print(f"Eng yuqori ko‘rsatkich: {max_per:.2f}%")
print(f"Eng past ko‘rsatkich: {min_per:.2f}%")
