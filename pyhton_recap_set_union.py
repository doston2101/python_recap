uzum = {"Laptop", "Phone", "Tablet", "Monitor", "Mouse"}
olcha = {"Phone", "Keyboard", "Laptop", "Printer"}
asaxiy = {"Tablet", "Mouse", "Camera", "Printer"}

#5/10 - 1 Uchala platformada mavjud
#barcha noyob mahsulotlarni birlashtir.
result = uzum.union(olcha, asaxiy)
print(result)

print("-----------------------------")

#2 Umumiy mahsulot turlari sonini aniqlagin.
print(f'count : {len(result)}')

# 6/10 - 3 Har bir platformadagi mahsulotlar sonini aniqlagin.
print(f'uzum : {len(uzum)}''\n',
      f'olcha : {len (olcha)}''\n',
      f'asaxiy : {len (asaxiy)}')
print("-----------------------------")

#4 Umumiy noyob mahsulotlar sonini top.
print(f'count : {len(result)}')
print("-----------------------------")

#5 Platformalardagi jami mahsulot soni bilan
# noyob mahsulotlar soni orasidagi farqni hisobla.

