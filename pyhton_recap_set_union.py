# 7/10
# - Uchala platformaning umumiy mahsulot bazasini yarat.
total_unique = uzum | olcha | asaxiy
print(total_unique)
print("-----------------------------")

# - Har bir platforma umumiy bazaning necha foizini tashkil qilishini hisobla.
uzum_share = (len(uzum) / len(total_unique)) * 100
olcha_share = (len(olcha) / len(total_unique)) * 100
asaxiy_share = (len(asaxiy) / len(total_unique)) * 100

print(f'uzum :{uzum_share:.2f}%''\n',
      f'olcha:{olcha_share:.2f}%''\n',
      f'asaxiy:{asaxiy_share:.2f}%')

# 8/10
# - Uchala platformadagi noyob mahsulotlar bazasini yarat.
print(total_unique)
print("-----------------------------")

# - Har bir platformaning umumiy bazaga qo‘shgan noyob mahsulotlarini aniqlash uchun tahlil qil.
only_uzum = uzum -(olcha | asaxiy)
only_olcha = olcha - (uzum| asaxiy)
only_asaxiy = asaxiy - (uzum | olcha)

print(f'onliy_uzum: {only_uzum}''\n',
      f'onliy_olcha: {only_olcha}''\n',
      f'onliy_asaxiy: {only_asaxiy}')
print("-----------------------------")

# - Har bir platforma uchun noyob mahsulotlar sonini hisobla.
print(f'onliy_uzum: {len(only_uzum)}')
print(f'onliy_olcha: {len(only_olcha)}')
