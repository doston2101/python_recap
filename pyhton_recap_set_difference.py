uzum = {
    'Laptop', 'Phone', 'Tablet', 'Monitor', 'Keyboard',
    'Mouse', 'Printer', 'Headphones', 'Smart Watch',
    'Camera', 'Power Bank', 'Flash Drive'
}

olcha = {
    'Laptop', 'Phone', 'Tablet', 'Mouse', 'Printer',
    'Headphones', 'Smart Watch', 'Microphone',
    'Router', 'Power Bank', 'SSD'
}

asaxiy = {
    'Laptop', 'Phone', 'Monitor', 'Keyboard', 'Mouse',
    'Camera', 'Microphone', 'Router', 'SSD',
    'Webcam', 'Projector', 'Flash Drive'
}

# 2. Topshiriqlar
# 1-topshiriq. Individual competitive advantage

# Har bir marketplace boshqa ikkita platformada mavjud bo‘lmagan qanday mahsulotlarga ega ekanini aniqlang.
# - Faqat Uzum mahsulotlari.
uzum_unique = uzum.difference(olcha.union(asaxiy))
print(f'uzum : {uzum_unique}')
# - Faqat Olcha mahsulotlari.
olcha_unique = olcha.difference(uzum.union(asaxiy))
print(f'olcha  :{olcha_unique}')
# - Faqat Asaxiy mahsulotlari.
asaxiy_unique = asaxiy.difference(uzum | olcha )
print(f'asaxiy : {asaxiy_unique}')

# 3-topshiriq. Exclusive product ratio
# Har bir platformaning faqat o‘zida mavjud mahsulotlari umumiy
#assortimentining necha foizini tashkil etishini hisoblang.

uzum_total = len(uzum)
olcha_total = len(olcha)
asaxiy_total = len(asaxiy)

uzum_exclusive = len(uzum_unique)
olcha_exclusive = len(olcha_unique)
asaxiy_exclusive = len(asaxiy_unique)

uzum_ratio = (uzum_exclusive / uzum_total) *100
olcha_ratio =(olcha_exclusive / olcha_total) * 100
asaxiy_ratio = (asaxiy_exclusive/ asaxiy_total) *100

print(f'uzum mahsulotlari umumiy assortimentining necha foizini tashkil etishini: {uzum_ratio:.2f}%''\n',
      f'olcha mahsulotlari umumiy assortimentining necha foizini tashkil etishini: {olcha_ratio:.2f}%''\n',
      f'asaxiy mahsulotlari umumiy assortimentining necha foizini tashkil etishini: {asaxiy_ratio:.2f}%')

# 4-topshiriq. Competitive gap analysis

# Uzum va Olcha o‘rtasidagi mahsulot assortimentidagi farqni ikki yo‘nalishda aniqlang:
# - Uzumda bor, Olchada yo‘q mahsulotlar.
uzum_true = uzum.difference(olcha)
print(f'Uzumda bor, Olchada yo\'q mahsulotlar: {uzum_true}')
# - Olchada bor, Uzumda yo‘q mahsulotlar.
olcha_true = olcha.difference(uzum)
print(f'Olchada bor, Uzumda yo\'q mahsulotlar: {olcha_true}')
# So‘ng qaysi platformaning eksklyuziv mahsulotlari ko‘proq ekanini aniqlang.
if len(uzum_true) > len(olcha_true):
    print('Uzumda eksklyuziv mahsulotlari ko\'proq')
else:
    print('Olchada eksklyuziv mahsulotlari ko\'proq')

# 5-topshiriq. Strategic market opportunity
# Uchala marketplace orasida hali hech qaysi platforma sotmayotgan mahsulotlar uchun yangi mahsulotlar ro‘yxatini yaratish imkonini beradigan algoritm tuzing.
# Bu topshiriqda mavjud DATA asosida yangi mahsulotlar ro‘yxatini shakllantirish mantig‘ini ishlab chiqing.

market_products = {
    'Phone',
    'Laptop',
    'TV',
    'Mouse',
    'Keyboard',
    'Printer',
    'Smart Watch',
    'Camera',
    'Tablet',
    'Headphones'
}

total_data = uzum.union(olcha.union(asaxiy))
print(f'total data :{total_data} ')

new_products = market_products.difference(total_data)
print(f'3 ta platformadagi umumiy maxsulatlar: {total_data}''\n',
      f'boshqa marketdagi maxsulotlar : {market_products}''\n',
      f'3 ta platformada yuq maxsulotlar: {new_products}''\n',
      f'3 ta platformada yuq maxsulotlar soni : {len(new_products)}')



