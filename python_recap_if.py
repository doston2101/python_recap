# 3-vazifa. Marketplace Business Status
# Har bir platformaning biznes holatini aniqlang.

# Qoidalar:
# 1. Agar marketplace faol bo‘lmasa, Inactive Marketplace.
# 2. Agar faol bo‘lsa va tushum rejasi bajarilgan bo‘lsa:
#    - Qaytarish foizi 5% yoki undan past bo‘lsa — Healthy Business.
#    - Aks holda — Revenue Achieved, but Return Risk Exists.
